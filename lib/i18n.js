function normalizeLocale(locale = DEFAULT_LOCALE) {
  return String(locale || DEFAULT_LOCALE).trim().toLowerCase().split(/[-_]/)[0];
}

function findLocaleConfig(locale = DEFAULT_LOCALE, { includeQa = true } = {}) {
  const normalized = normalizeLocale(locale);
  const candidates = includeQa ? [...SUPPORTED_LOCALES, ...LOCALE_QA_MATRIX] : SUPPORTED_LOCALES;
  return candidates.find((entry) => entry.code === normalized) || SUPPORTED_LOCALES[0];
}

export function getLocaleConfig(locale = DEFAULT_LOCALE) {
  return findLocaleConfig(locale, { includeQa: true });
}

/**
 * @param {{ locale?: string, acceptLanguage?: string }} [options]
 */
export function resolveLocale({ locale, acceptLanguage } = {}) {
  if (locale) return getLocaleConfig(locale);
  const accepted = String(acceptLanguage || '')
    .split(',')
    .map((part) => part.trim().split(';')[0])
    .filter(Boolean);
  for (const candidate of accepted) {
    const config = findLocaleConfig(candidate, { includeQa: false });
    if (config.code !== DEFAULT_LOCALE || normalizeLocale(candidate) === DEFAULT_LOCALE) return config;
  }
  return getLocaleConfig(DEFAULT_LOCALE);
}

export function getTranslation(locale = DEFAULT_LOCALE, key) {
  const normalizedLocale = getLocaleConfig(locale).code;
  return CORE_TRANSLATIONS[normalizedLocale]?.[key] || CORE_TRANSLATIONS[DEFAULT_LOCALE][key] || key;
}

export function getDictionary(locale = DEFAULT_LOCALE) {
  const config = getLocaleConfig(locale);
  return {
    ...CORE_TRANSLATIONS[DEFAULT_LOCALE],
    ...(CORE_TRANSLATIONS[config.code] || {}),
  };
}

export function formatLocalizedDate(date, locale = DEFAULT_LOCALE, options = {}) {
  const parsed = date instanceof Date ? date : new Date(date);
  if (!Number.isFinite(parsed.getTime())) return null;
  return new Intl.DateTimeFormat(getLocaleConfig(locale).code, {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    ...options,
  }).format(parsed);
}

export function formatLocalizedCurrency(amount, locale = DEFAULT_LOCALE, currency = DEFAULT_CURRENCY) {
  const number = Number(amount);
  if (!Number.isFinite(number)) return null;
  return new Intl.NumberFormat(getLocaleConfig(locale).code, {
    style: 'currency',
    currency: currency || DEFAULT_CURRENCY,
    maximumFractionDigits: 0,
  }).format(number);
}

/**
 * @param {{ locale?: string, acceptLanguage?: string, sampleDate?: Date|string, sampleAmount?: number, currency?: string }} [options]
 */
export function buildLocalePayload({ locale, acceptLanguage, sampleDate, sampleAmount, currency = DEFAULT_CURRENCY } = {}) {
  const config = resolveLocale({ locale, acceptLanguage });
  const contentTranslation = config.code === DEFAULT_LOCALE
    ? 'complete'
    : CORE_TRANSLATIONS[config.code]
      ? 'partial'
      : 'fallback-only';
  return {
    locale: config.code,
    name: config.name,
    dir: config.dir,
    defaultLocale: DEFAULT_LOCALE,
    contentTranslation,
    dictionary: getDictionary(config.code),
    formatting: {
      date: sampleDate ? formatLocalizedDate(sampleDate, config.code) : null,
      currency: sampleAmount !== undefined && sampleAmount !== null
        ? formatLocalizedCurrency(sampleAmount, config.code, currency)
        : null,
    },
    fallbackPolicy: 'missing-keys-fall-back-to-English-and-unavailable-states-remain-explicit',
  };
}

export function buildLocaleQaReport({ sampleDate = '2026-06-01', sampleAmount = 120, currency = DEFAULT_CURRENCY } = {}) {
  return {
    status: 'qa-matrix-ready',
    publicLocales: SUPPORTED_LOCALES.map(({ code, name, dir }) => ({ code, name, dir })),
    qaLocales: LOCALE_QA_MATRIX.map((config) => ({
      code: config.code,
      name: config.name,
      dir: config.dir,
      public: config.public,
      contentTranslation: config.contentTranslation,
      dictionaryPolicy: 'falls-back-to-English-until-full-translation-is-approved',
      formatting: {
        date: formatLocalizedDate(sampleDate, config.code),
        currency: formatLocalizedCurrency(sampleAmount, config.code, currency),
      },
      runtimeExpectation: {
        htmlLang: config.code,
        htmlDir: config.dir,
      },
    })),
    requiredDirections: ['ltr', 'rtl'],
  };
}

export function getI18nReadiness() {
  const qaReport = buildLocaleQaReport();
  return {
    supportedLocales: SUPPORTED_LOCALES.map(({ code, name, dir }) => ({ code, name, dir })),
    qaLocales: qaReport.qaLocales.map(({ code, name, dir, public: isPublic, contentTranslation }) => ({
      code,
      name,
      dir,
      public: isPublic,
      contentTranslation,
    })),
    defaultLocale: DEFAULT_LOCALE,
    rtlSupported: [...SUPPORTED_LOCALES, ...LOCALE_QA_MATRIX].some((locale) => locale.dir === 'rtl'),
    ltrSupported: [...SUPPORTED_LOCALES, ...LOCALE_QA_MATRIX].some((locale) => locale.dir === 'ltr'),
    qaMatrixStatus: qaReport.status,
    status: 'infrastructure-ready',
    contentTranslation: 'partial',
    fallbackPolicy: 'missing-keys-fall-back-to-English-and-unavailable-states-remain-explicit',
    dictionaries: Object.fromEntries(
      Object.entries(CORE_TRANSLATIONS).map(([locale, values]) => [locale, Object.keys(values).length])
    ),
  };
}
